# ── RAG Tool ─────────────────────────────────────────────────────
@tool
def search_knowledge(query: str) -> str:
    """Пошук інформації у базі знань компанії (ERP, фінанси, SAF-T UA).
    
    Використовуйте цей інструмент, коли потрібна довідкова
    інформація, факти, правила обліку, регламенти або термінологія з бази знань.
    НЕ використовуйте для математичних обчислень або перевірки поточних залишків на складах.
    
    Args:
        query: Пошуковий запит.
        
    Returns:
        Топ-3 релевантних документи з бази знань.
    """
    results = knowledge_base.query(query_texts=[query], n_results=3)
    
    if not results['documents'] or not results['documents'][0]:
        return "Інформацію не знайдено."
        
    docs = results['documents'][0]
    return '\n---\n'.join(docs)

if __name__ == "__main__":
    result = search_knowledge.invoke({'query': 'правила для контрагентів SAF-T UA'})
